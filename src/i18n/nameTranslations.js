/**
 * Returns the localised name for any station, line, or landmark.
 * Falls back to the original English name when the target language is
 * 'en' or when no translation exists.
 *
 * @param {string} lang  'en' | 'hi' | 'bn'
 * @param {string} englishName  The English name (exactly as it appears
 *   in the data files — e.g. 'Blue Line', 'Dakshineshwar', 'Victoria Memorial').
 * @returns {string} The translated name, or `englishName` unchanged.
 */
export function translateName(lang, englishName) {
  if (!englishName || lang === 'en') return englishName;
  const entry = allTranslations.get(englishName);
  return entry?.[lang] ?? englishName;
}
