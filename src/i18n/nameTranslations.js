// ── Merged lookup table ──────────────────────────────────────────────
// Built once at module load — merges lines, stations, and landmarks
// into a single Map for O(1) lookups.
const allTranslations = new Map();
for (const dict of [lineNames, stationNames, landmarkNames]) {
  for (const [en, translations] of Object.entries(dict)) {
    allTranslations.set(en, translations);
  }
}

